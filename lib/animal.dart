class Animal {
  String id;
  String name;
  String species;
  int age;
  String race;
  double weight;
  bool isAttended;

  Animal({
    required this.id,
    required this.name,
    required this.species,
    required this.age,
    required this.race,
    required this.weight,
    required this.isAttended
  });
}